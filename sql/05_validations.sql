-- =====================================================================
-- 05_validations.sql   |   Deliverable 5: data quality
--
-- Two kinds of problems:
--   FATAL   -> row is quarantined (STG_MEMBER.REJECT_REASON is not null). The job continues.
--   WARNING -> row is loaded, but reported.
-- Plus job-level checks: counts must reconcile, reject rate must be small.
-- =====================================================================

-- ---- 1. FATAL: mandatory fields, bad dates, unknown country (rules live in 02) ----
SELECT REJECT_REASON, COUNT(*) AS ROWS_REJECTED
FROM STG_MEMBER WHERE BATCH_ID = $BATCH_ID AND REJECT_REASON IS NOT NULL
GROUP BY 1;
-- e.g. enrollment 20211313 (month 13) -> ENROLLMENT_DATE_MISSING_OR_INVALID; country UAE -> COUNTRY_UNKNOWN

-- ---- 2. WARNINGS: one rule per line, so the next rule is easy to add ----
CREATE OR REPLACE VIEW DQ_MEMBER_WARNINGS AS
SELECT BATCH_ID, MEMBER_ID, MEMBER_NAME, 'DOB_MISSING_OR_INVALID'  AS RULE FROM STG_MEMBER WHERE REJECT_REASON IS NULL AND DOB IS NULL        -- text 'NULL' or lost digits
UNION ALL SELECT BATCH_ID, MEMBER_ID, MEMBER_NAME, 'DOB_IN_FUTURE'             FROM STG_MEMBER WHERE REJECT_REASON IS NULL AND DOB > CURRENT_DATE
UNION ALL SELECT BATCH_ID, MEMBER_ID, MEMBER_NAME, 'AGE_IMPLAUSIBLE'           FROM STG_MEMBER WHERE REJECT_REASON IS NULL AND AGE NOT BETWEEN 0 AND 110
UNION ALL SELECT BATCH_ID, MEMBER_ID, MEMBER_NAME, 'FLIGHT_BEFORE_ENROLLMENT'  FROM STG_MEMBER WHERE REJECT_REASON IS NULL AND LAST_FLIGHT_DATE < ENROLLMENT_DATE
UNION ALL SELECT BATCH_ID, MEMBER_ID, MEMBER_NAME, 'FLIGHT_DATE_IN_FUTURE'    FROM STG_MEMBER WHERE REJECT_REASON IS NULL AND LAST_FLIGHT_DATE > CURRENT_DATE
UNION ALL SELECT BATCH_ID, MEMBER_ID, MEMBER_NAME, 'UNKNOWN_TIER'              FROM STG_MEMBER WHERE REJECT_REASON IS NULL AND COALESCE(TIER_CODE, '') NOT IN ('PLT','GLD','SLV')
UNION ALL SELECT BATCH_ID, MEMBER_ID, MEMBER_NAME, 'BAD_ACTIVE_FLAG'           FROM STG_MEMBER WHERE REJECT_REASON IS NULL AND IS_ACTIVE IS NOT NULL AND IS_ACTIVE NOT IN ('A','I')
-- same Member_Id with different names, and the reverse (the spec calls Member Name a key column; names can repeat)
UNION ALL SELECT BATCH_ID, MEMBER_ID, MIN(MEMBER_NAME), 'SAME_ID_DIFFERENT_NAME'
          FROM STG_MEMBER WHERE REJECT_REASON IS NULL GROUP BY BATCH_ID, MEMBER_ID HAVING COUNT(DISTINCT UPPER(MEMBER_NAME)) > 1
UNION ALL SELECT BATCH_ID, MIN(MEMBER_ID), MEMBER_NAME, 'SAME_NAME_DIFFERENT_ID'
          FROM STG_MEMBER WHERE REJECT_REASON IS NULL GROUP BY BATCH_ID, MEMBER_NAME HAVING COUNT(DISTINCT MEMBER_ID) > 1;

SELECT RULE, COUNT(*) FROM DQ_MEMBER_WARNINGS WHERE BATCH_ID = $BATCH_ID GROUP BY 1;

-- ---- 3. KEY UNIQUENESS ----
-- (a) Same member twice in a batch is NOT an error, it is normal (a mover, a re-send): latest wins.
--     But if two rows tie on the version too, the winner is chosen only by file order -> have a look.
SELECT MEMBER_ID, VERSION_KEY, COUNT(*) AS TIED_ROWS
FROM STG_MEMBER WHERE BATCH_ID = $BATCH_ID AND REJECT_REASON IS NULL
GROUP BY 1, 2 HAVING COUNT(*) > 1;

-- (b) After the load MEMBER_CURRENT must have ZERO duplicate keys.                  -> expect 0 rows
SELECT MEMBER_ID, COUNT(*) FROM MEMBER_CURRENT GROUP BY 1 HAVING COUNT(*) > 1;

-- (c) A member must live in exactly ONE country table:
--     rows over all TABLE_* must equal MEMBER_CURRENT.                              -> expect equal numbers
SELECT (SELECT COUNT(*) FROM MEMBER_CURRENT) AS CURRENT_ROWS,
       (SELECT SUM(ROW_COUNT) FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME LIKE 'TABLE\\_%' ESCAPE '\\') AS COUNTRY_TABLE_ROWS;

-- ---- 4. RECONCILIATION: nothing may disappear silently ----
--   RAW_ROWS must equal STG_ROWS.   STG_ROWS = REJECTED + SUPERSEDED + WINNERS.
WITH c AS (
  SELECT
    (SELECT COUNT(*) FROM RAW_MEMBER WHERE REC_TYPE = 'D' AND BATCH_ID = $BATCH_ID)                AS RAW_ROWS,
    (SELECT COUNT(*) FROM STG_MEMBER WHERE BATCH_ID = $BATCH_ID)                                   AS STG_ROWS,
    (SELECT COUNT(*) FROM STG_MEMBER WHERE BATCH_ID = $BATCH_ID AND REJECT_REASON IS NOT NULL)     AS REJECTED,
    (SELECT COUNT(*) FROM BATCH_WINNERS)                                                           AS WINNERS
)
SELECT *, STG_ROWS - REJECTED - WINNERS AS SUPERSEDED FROM c;

-- ---- 5. CIRCUIT BREAKER: a few bad rows are normal, a bad FILE is not ----
-- The orchestrator fails the run (so wrong country tables are never published) if this says FAIL.
SELECT IFF(AVG(IFF(REJECT_REASON IS NOT NULL, 1, 0)) > 0.01, 'FAIL: more than 1% rejected', 'OK') AS REJECT_RATE_CHECK
FROM STG_MEMBER WHERE BATCH_ID = $BATCH_ID;

-- ---- 6. REDEMPTION CHECKS ----
SELECT 'TXN_ID_MISSING'  AS RULE, COUNT(*) AS ROWS_FOUND FROM BATCH_TXN WHERE TXN_ID IS NULL
UNION ALL SELECT 'BAD_TXN_DATE',   COUNT(*) FROM BATCH_TXN WHERE TXN_DATE IS NULL
UNION ALL SELECT 'BAD_MILES',      COUNT(*) FROM BATCH_TXN WHERE MILES_REDEEMED IS NULL OR MILES_REDEEMED <= 0
UNION ALL SELECT 'UNKNOWN_STATUS', COUNT(*) FROM BATCH_TXN WHERE STATUS NOT IN ('COMPLETED','PENDING','CANCELLED','FAILED')
UNION ALL SELECT 'ORPHAN_MEMBER',  COUNT(*) FROM FACT_REDEMPTION WHERE BATCH_ID = $BATCH_ID AND MEMBER_ID NOT IN (SELECT MEMBER_ID FROM MEMBER_CURRENT);
